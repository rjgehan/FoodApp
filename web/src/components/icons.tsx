/** What a named icon takes: an <svg>'s props, without the name. */
type GlyphProps = Omit<SVGProps<SVGSVGElement>, 'name'>;

const named = (name: IconName) => {
  const C = (p: GlyphProps) => <Icon {...p} name={name} />;
  C.displayName = `Icon(${name})`;
  return C;
};

